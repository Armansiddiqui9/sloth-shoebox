def seed(conn: sqlite3.Connection) -> int:
    """Wipe all four tables and insert the demo data. Returns the transaction count."""
    for table in ("splits", "ingest_artifacts", "quarantined_parses", "transactions"):
        conn.execute(f"DELETE FROM {table}")

    rng = random.Random(2026)
    linked: dict[str, str] = {}
    for n, (raw, norm, amount, when, cat, app, doc, status, conf, src, extra) in enumerate(_ROWS):
        row = insert_transaction(
            conn,
            {
                "vendor_raw": raw,
                "vendor_normalized": norm,
                "amount": amount,
                "datetime_local": when,
                "category": cat,
                "payment_app": app,
                "doc_type": doc,
                "status": status,
                "confidence": conf,
                "source_file": src,
                "payment_ref": f"UPI/{rng.randrange(10**11, 10**12)}/Payment/{n + 1:06d}",
                "content_hash": f"phash:{rng.getrandbits(48):012x}",
                **extra,
            },
        )
        linked.setdefault(src, row["id"])
        if norm == "bookmyshow":
            # Three-way split so the splits endpoints have data out of the box.
            replace_splits(conn, row["id"], [("Aman", 160.0), ("Priya", 160.0), ("Riya", 160.0)])
            conn.execute(
                "UPDATE splits SET settled = 1 WHERE transaction_id = ? AND participant = 'Riya'",
                (row["id"],),
            )

    for file_name, file_type, stage, conf, parse, error, when in _ARTIFACTS:
        conn.execute(
            "INSERT INTO ingest_artifacts (id, file_name, file_type, content_hash, stage, "
            "confidence, parse_result_json, transaction_id, error_message, created_at, updated_at)"
            " VALUES (?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?)",
            (
                new_id(),
                file_name,
                file_type,
                f"phash:{rng.getrandbits(48):012x}",
                stage,
                conf,
                json.dumps(parse),
                linked.get(file_name) if stage == "committed" else None,
                error,
                when,
                when,
            ),
        )
    return len(_ROWS)
